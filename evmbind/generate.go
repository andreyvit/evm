// Generate emits direct Go wrappers for the schema New builds from the same
// source and options, including Selective, Only and Omit. nativeImport is the
// Go import path of the bound package; runtime binding options are ignored.
func Generate(path, nativeImport, outputPackage string, files fs.FS, opt Options) ([]byte, error) {
	if opt.NativePackage == "" {
		opt.NativePackage = nativeImport
	}
	s, err := parseOptions(path, files, opt.Only, opt.Selective || opt.Only != nil, opt)
	if err != nil {
		return nil, err
	}
	return generateSource(s, nativeImport, outputPackage)
}

func generateSource(s *source, nativeImport, outputPackage string) ([]byte, error) {
	if s.hasGenericInstances() {
		return nil, fmt.Errorf("generic native instances do not support generated bindings")
	}
	if !token.IsIdentifier(outputPackage) {
		return nil, fmt.Errorf("invalid output package %q", outputPackage)
	}
	var b bytes.Buffer
	line := func(pattern string, a ...any) { fmt.Fprintf(&b, pattern+"\n", a...) }
	line("// Code generated by evmbind. DO NOT EDIT.\n//go:build !evmreflect\n\npackage %s", outputPackage)
	line("import (")
	ns := sortedNodes(s)
	ids := map[*node]string{}
	hasAPI := false
	hasNamed := false
	external := map[string]string{}
	for _, n := range ns {
		if n.genericType != nil {
			types.TypeString(n.genericType, func(p *types.Package) string { external[s.nativeTypePath(p)] = ""; return "" })
		}
		if n.modelType != nil {
			types.TypeString(n.modelType, func(p *types.Package) string { external[s.nativeTypePath(p)] = ""; return "" })
		}
		if n.nativeImport != "" {
			external[n.nativeImport] = ""
		}
	}
	var paths []string
	for path := range external {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for i, path := range paths {
		external[path] = fmt.Sprintf("dep%d", i)
	}
	hasHost := false
	hasDirect := false
	for index, n := range ns {
		switch {
		case n.kind == nodeRecord && n.model.row.Mutable:
			ids[n] = fmt.Sprintf("MutableModel%d", index)
		case n.kind == nodeRetainedFunction:
			ids[n] = fmt.Sprintf("Function%d", index)
			hasHost = true
		case n.kind == nodeNativeFunction && !n.named:
			ids[n] = fmt.Sprintf("NativeFunction%d", index)
		case n.nativeImport != "":
			ids[n] = fmt.Sprintf("Imported%d", index)
		case (n.kind == nodePointer || n.kind == nodeRecord && n.elem != nil) && n.elem.nativeImport != "":
			ids[n] = fmt.Sprintf("PtrImported%d", index)
		case n.named:
			ids[n] = "Type" + n.name
		case n.kind == nodeStruct && !n.named:
			ids[n] = fmt.Sprintf("Struct%d", index)
		case n.kind == nodeSlice || n.kind == nodeMap:
			ids[n] = fmt.Sprintf("Collection%d", index)
		case n.inputOnly():
			ids[n] = n.kind.String()
		case n.kind == nodePointer && !n.elem.named:
			ids[n] = fmt.Sprintf("Pointer%d", index)
		case n.kind == nodePointer || n.kind == nodeRecord && n.elem != nil:
			ids[n] = "Ptr" + n.elem.name
		default:
			ids[n] = "Scalar" + strings.ToUpper(n.name[:1]) + n.name[1:]
		}
		hasNamed = hasNamed || n.named
		hasAPI = hasAPI || n.named && n.nativeImport == ""
	}
	for _, op := range s.ops {
		hasHost = hasHost || op.recv == nil && !op.packageFunction
		hasDirect = hasDirect || op.directOpcode() != 0
	}
	hasFields, hasPointers := false, false
	pointerElements := make(map[*node]bool)
	for _, n := range ns {
		hasFields = hasFields || n.kind == nodeStruct
		hasPointers = hasPointers || n.kind == nodePointer || n.kind == nodeSlice && !isModelSlice(n) || n.kind == nodeMap
		if n.kind == nodePointer {
			pointerElements[n.elem] = true
		}
	}
	if hasNamed {
		line("%q", "reflect")
	}
	if hasFields || hasPointers {
		line("%q", "unsafe")
	}
	if hasAPI || hasFields || hasPointers {
		line("")
	}
	if hasAPI {
		line("api %q", nativeImport)
	}
	for _, path := range paths {
		line("%s %q", external[path], path)
	}
	line("%q", "github.com/andreyvit/evm/evmbind")
	if hasFields {
		line("%q", "github.com/andreyvit/evm/nativebind")
	}

	if hasHost || hasDirect {
		line("%q", "github.com/andreyvit/evm")
	}
	if len(ns) > 0 {
		line("%q", "github.com/andreyvit/evm/values")
	}
	line(")")
	var typ func(*node) string
	typ = func(n *node) string {
		if n.genericType != nil {
			return types.TypeString(n.genericType, func(p *types.Package) string { return external[s.nativeTypePath(p)] })
		}
		if n.modelType != nil {
			return types.TypeString(n.modelType, func(p *types.Package) string { return external[s.nativeTypePath(p)] })
		}
		if n.nativeImport != "" {
			return external[n.nativeImport] + "." + n.nativeName
		}
		if n.kind == nodeRetainedFunction {
			return "*evm.Callable"
		}
		if n.named {
			return "api." + n.name
		}
		if n.kind == nodePointer || n.kind == nodeRecord && n.elem != nil {
			return "*" + typ(n.elem)
		}
		if n.kind == nodeSlice {
			return "[]" + typ(n.elem)
		}
		if n.kind == nodeNativeFunction {
			params := make([]string, len(n.functionArgs))
			results := make([]string, len(n.functionOuts))
			for i, arg := range n.functionArgs {
				params[i] = typ(arg)
			}
			for i, result := range n.functionOuts {
				results[i] = typ(result)
			}
			result := "func(" + strings.Join(params, ",") + ")"
			if len(results) == 1 {
				result += " " + results[0]
			} else if len(results) > 1 {
				result += " (" + strings.Join(results, ",") + ")"
			}
			return result
		}
		if n.kind == nodeMap {
			return "map[" + typ(n.key) + "]" + typ(n.elem)
		}
		return n.name
	}
	for _, n := range ns {
		i := ids[n]
		line("func read%s(f *evmbind.Frame,v values.Value) %s {", i, typ(n))
		switch n.kind {
		case nodeTimestamp:
			line("return v.AsTime()")
		case nodeRecord:
			if n.native.Kind() == reflect.Pointer {
				line("return f.ModelArgument(%q,v).(%s)", n.name, typ(n))
			} else {
				line("return evmbind.ModelValueArgument[%s](f,%q,v)", typ(n), n.name)
			}
		case nodeError:
			line("return f.DecodeError(v)")
		case nodeAny:
			line("return f.DecodeAny(v)")
		case nodeSlice:
			if isModelSlice(n) {
				line("if v.SliceData()==nil{return nil};view:=v.NativeSlice();if view==nil || view.Layout.GoType.Elem()!=reflect.TypeFor[%s](){panic(%q)};return unsafe.Slice((*%s)(view.Data),view.Capacity)[:view.Length]", typ(n.elem), "model slice "+n.name+" requires matching native storage; explicit conversion required", typ(n.elem))
				break
			}
			line("return (%s)(unsafe.Slice((*%s)(evmbind.NativeSliceData(v,reflect.TypeFor[%s]())),int(v.SliceCap()))[:int(v.SliceLen())])", typ(n), typ(n.elem), typ(n.elem))
		case nodeMap:
			line("return *(*%s)(unsafe.Pointer(&v.P))", typ(n))
		case nodeRetainedFunction:
			if n.boxedFunction {
				line("return f.BoxedFunction(v)")
			} else {
				line("return f.Function(v)")
			}
		case nodeNativeFunction:
			line("return f.DecodeNativeFunction(%q,v).(%s)", n.name, typ(n))
		case nodeCallback:
			line("return f.Callback(v)")
		case nodeStruct:
			if len(n.omittedFields) > 0 {
				line("var x %s;if snapshot:=evmbind.Field(v,%d,false).P;snapshot!=nil{x=*(*%s)(snapshot)}", typ(n), n.shape.Cells-1, typ(n))
				for _, k := range n.fields {
					line("x.%s=read%s(f,evmbind.Field(v,%d,%t))", k.name, ids[k.t], k.offset, k.t.shape.Aggregate())
				}
				line("return x")
			} else {
				line("return %s{", typ(n))
				for fieldIndex, k := range n.fields {
					cell := fmt.Sprintf("evmbind.Field(v,%d,%t)", k.offset, k.t.shape.Aggregate())
					if n.shape.CellStruct != nil {
						cell = fmt.Sprintf("f.CellField(%q,v,%d)", n.name, fieldIndex)
					}
					line("%s:read%s(f,%s),", k.name, ids[k.t], cell)
				}
				line("}")
			}
		case nodePointer:
			line("if v.P==nil{return nil};if v.R!=values.NativeAddress{panic(%q)};return (%s)(v.P)", "native pointer "+n.name+" requires native storage", typ(n))
		case nodeInterface:
			if n.imported != nil {
				line("if v==(values.Value{}){return nil};return f.DecodeTypedInterface(%q,v).(%s)", n.name, typ(n))
			} else {
				line("if v==(values.Value{}){return nil};return f.DecodeInterface(v).(%s)", typ(n))
			}
		default:
			line("return %s", scalarRead(nativeKind(n), typ(n), "v"))
		}
		line("}")
		if n.inputOnly() {
			continue
		}
		line("func write%s(f *evmbind.Frame,x %s) values.Value{", i, typ(n))
		switch n.kind {
		case nodeTimestamp:
			line("return f.Time(x)")
		case nodeRecord:
			if n.native.Kind() == reflect.Pointer {
				line("return f.ModelResult(%q,x)", n.name)
			} else {
				line("return evmbind.ModelValueResult(f,%q,x)", n.name)
			}
		case nodeAny, nodeError:
			line("return f.EncodeAny(x)")
		case nodeSlice:
			if isModelSlice(n) {
				line("return f.NativeModelSliceResult(%q,unsafe.Pointer(unsafe.SliceData(x)),len(x),cap(x))", n.name)
				break
			}
			line("if uint64(cap(x))>1<<32-1 {panic(%q)};return values.SliceValue(unsafe.Pointer(unsafe.SliceData(x)),uint32(len(x)),uint32(cap(x)))", "native slice exceeds VM capacity")
		case nodeMap:
			line("return values.Value{P:*(*unsafe.Pointer)(unsafe.Pointer(&x))}")
		case nodeNativeFunction:
			line("return f.EncodeNativeFunction(%q,x)", n.name)
		case nodeRetainedFunction:
			line("return f.EncodeFunction(%q,x)", n.name)
		case nodeStruct:
			if n.shape.CellStruct != nil {
				line("return f.PackCell(%q,[2]values.Value{", n.name)
				for _, k := range n.fields {
					line("write%s(f,x.%s),", ids[k.t], k.name)
				}
				line("})")
			} else {
				line("v:=values.Value{P:f.New(%d)};store%s(f,v,x);return v", n.shape.Cells, i)
			}
		case nodePointer:
			line("if x==nil{return values.Value{}};return values.Value{R:values.NativeAddress,P:unsafe.Pointer(x)}")
		case nodeInterface:
			if n.imported != nil {
				line("return f.EncodeTypedInterface(%q,x)", n.name)
			} else {
				line("return f.EncodeInterface(x)")
			}
		case nodeString:
			line("return f.String(string(x))")
		default:
			line("return %s", scalarWrite(nativeKind(n), "x"))
		}
		line("}")
		if n.kind == nodeStruct && n.shape.CellStruct == nil {
			line("func store%s(f *evmbind.Frame,v values.Value,x %s){", i, typ(n))
			if len(n.omittedFields) > 0 {
				line("if err:=f.ChargeAllocation(uint64(unsafe.Sizeof(x)));err!=nil{panic(err)};snapshot:=x;*(*values.Value)(values.CellAt(v.P,%d))=values.Value{P:unsafe.Pointer(&snapshot)}", n.shape.Cells-1)
			}
			for _, k := range n.fields {
				if k.t.kind == nodeStruct && k.t.shape.CellStruct == nil {
					line("store%s(f,values.Value{P:values.CellAt(v.P,%d)},x.%s)", ids[k.t], k.offset, k.name)
				} else if k.t.kind == nodeRecord && k.t.shape.Aggregate() {
					line("evmbind.StoreModelValue(f,%q,values.CellAt(v.P,%d),x.%s)", k.t.name, k.offset, k.name)
				} else {
					line("*(*values.Value)(values.CellAt(v.P,%d))=write%s(f,x.%s)", k.offset, ids[k.t], k.name)
				}
			}
			line("}")
		} else if pointerElements[n] {
			line("func store%s(f *evmbind.Frame,v values.Value,x %s){*(*values.Value)(v.P)=write%s(f,x)}", i, typ(n), i)
		}
	}
	for _, n := range ns {
		if n.kind != nodeStruct {
			continue
		}
		var fields []nativebind.FieldSpec
		for _, f := range n.fields {
			fields = append(fields, nativebind.FieldSpec{Name: f.name, Type: typ(f.t), Kind: nativeKind(f.t)})
		}
		nativebind.GenerateFields(&b, "fields"+ids[n], typ(n), fields)
	}
	line("var Bindings = evmbind.Static{Fingerprint:%q,", s.fingerprint)
	if hasFields {
		line("Fields:map[string]*nativebind.GeneratedFields{")
		for _, n := range ns {
			if n.kind == nodeStruct {
				line("%q:&fields%s,", n.name, ids[n])
			}
		}
		line("},")
	}
	if hasNamed {
		line("Types:map[string]reflect.Type{")
		for _, n := range ns {
			if n.named {
				line("%q:reflect.TypeFor[%s](),", n.name, typ(n))
			}
		}
		line("},")
	}
	line("Calls:map[string]evmbind.Wrapper{")
	ops := append([]*operation{}, s.ops...)
	for _, n := range ns {
		if n.imported == nil {
			ops = append(ops, n.methods...)
		}
	}
	for _, op := range ops {
		line("%q:func(f *evmbind.Frame){", op.key)
		var params, results, args, lhs []string
		for i, n := range op.args {
			params = append(params, typ(n))
			idx := i
			if op.recv != nil {
				idx++
			}
			if n.kind == nodeNativeFunction {
				if b := op.callbackBorrow; b != nil && b.argument == i {
					args = append(args, fmt.Sprintf("f.DecodeBorrowedCallback(%q,f.CallArgument(%d),%q).(%s)", n.name, idx, b.domain, typ(n)))
				} else {
					args = append(args, fmt.Sprintf("f.DecodeNativeCallback(%q,f.CallArgument(%d)).(%s)", n.name, idx, typ(n)))
				}
			} else {
				args = append(args, fmt.Sprintf("read%s(f,f.CallArgument(%d))", ids[n], idx))
			}
		}
		for i, n := range op.outs {
			results = append(results, typ(n))
			lhs = append(lhs, fmt.Sprintf("r%d", i))
		}
		if op.variadic {
			params[len(params)-1] = "..." + typ(op.args[len(op.args)-1].elem)
			args[len(args)-1] += "..."
		}
		var recv string
		if op.packageFunction {
			recv = fmt.Sprintf("f.Host.(func(%s)(%s))", strings.Join(params, ","), strings.Join(results, ","))
		} else if op.recv == nil {
			params = append([]string{"*evm.VM"}, params...)
			args = append([]string{"f.VM"}, args...)
			recv = fmt.Sprintf("f.Host.(interface{%s(%s)(%s)})", op.name, strings.Join(params, ","), strings.Join(results, ","))
		} else if op.recv.kind == nodeInterface {
			recv = "f.Receiver.(" + typ(op.recv) + ")"
		} else {
			recv = fmt.Sprintf("read%s(f,f.CallArgument(0))", ids[op.recv])
		}
		target := recv
		if !op.packageFunction {
			target += "." + op.nativeMethod()
		}
		writeInvocation(line, target, args, lhs)
		if op.byteBorrow != nil {
			line("f.SetBorrowedBytesResult(0,r0)")
		} else if b := op.callbackBorrow; b != nil && b.argument < 0 {
			line("f.SetCallResult(0,f.EncodeBorrowedIterator(%q,r0,%q))", op.outs[0].name, b.domain)
		} else {
			for i, n := range op.outs {
				line("f.SetCallResult(%d,write%s(f,r%d))", i, ids[n], i)
			}
		}
		line("},")
	}
	if hasDirect {
		line("},")
		line("Direct: map[string]evmbind.DirectFactory{")
		for _, op := range s.ops {
			if op.directOpcode() != 0 {
				writeDirect(line, op, ids, typ)
			}
		}
	}
	line("}}")
	return imports.Process("bindings_gen.go", b.Bytes(), &imports.Options{FormatOnly: true, Comments: true, TabIndent: true, TabWidth: 8})
}
func Field(v values.Value, offset uint64, aggregate bool) values.Value {
	p := values.CellAt(v.P, offset)
	if aggregate {
		return values.Value{P: p}
	}
	if p == nil {
		return values.Value{}
	}
	return *(*values.Value)(p)
}

func nativeKind(n *node) reflect.Kind {
	if n.kind == nodeTimestamp {
		return reflect.Struct
	}
	if n.kind == nodeRecord && n.nativeLayout != nil {
		return n.native.Kind()
	}

	if n.kind == nodeNativeFunction {
		return reflect.Func
	}
	if n.kind == nodeRetainedFunction {
		return reflect.Pointer
	}
	switch n.shape.LogicalKind() {
	case values.BoolKind:
		return reflect.Bool
	case values.IntKind:
		switch n.kind {
		case nodeInt:
			return reflect.Int
		case nodeInt8:
			return reflect.Int8
		case nodeInt16:
			return reflect.Int16
		case nodeInt32:
			return reflect.Int32
		default:
			return reflect.Int64
		}
	case values.UintKind:
		switch n.kind {
		case nodeUint:
			return reflect.Uint
		case nodeUint8:
			return reflect.Uint8
		case nodeUint16:
			return reflect.Uint16
		case nodeUint32:
			return reflect.Uint32
		default:
			return reflect.Uint64
		}
	case values.FloatKind:
		if n.shape.Bits == 32 {
			return reflect.Float32
		}
		return reflect.Float64
	case values.StringKind:
		return reflect.String
	case values.PointerKind:
		return reflect.Pointer
	case values.StructKind:
		return reflect.Struct
	case values.SliceKind:
		return reflect.Slice
	case values.MapKind:
		return reflect.Map
	case values.InterfaceKind:
		return reflect.Interface
	default:
		panic("unsupported native field kind")
	}
}
