// Command coveragegen derives the instrumented interpreter from execute.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

func main() {
	data, err := os.ReadFile("evm.go")
	must(err)
	src := string(data)
	start := strings.Index(src, "func (vm *VM) execute(")
	end := strings.Index(src[start:], "\nfunc (vm *VM) invokeNative(") + start
	body := src[start:end]
	body = strings.Replace(body, " execute(", " executeCovered(", 1)
	body = strings.ReplaceAll(body, "ins := f.Code[cur.pc]", `ins := vm.coverage.instruction(cur.function, cur.pc)`)
	body = strings.ReplaceAll(body, "ins = f.Code[cur.pc]", `ins = vm.coverage.instruction(cur.function, cur.pc)`)
	// Each conditional jump has one PC update. Evaluate its condition once.
	lines := strings.Split(body, "\n")
	for i, line := range lines {
		if !strings.Contains(line, "cur.pc +=") || i == 0 {
			continue
		}
		prev := lines[i-1]
		trimmed := strings.TrimSpace(prev)
		if !strings.HasPrefix(trimmed, "if ") {
			continue
		}
		cond := strings.TrimSuffix(strings.TrimPrefix(trimmed, "if "), " {")
		lines[i-1] = prev[:len(prev)-len(strings.TrimLeft(prev, "\t"))] + "if vm.coverage.branch(cur.function, cur.pc-1, " + cond + ") {"
	}
	body = strings.Join(lines, "\n")
	out, err := format.Source([]byte("// Code generated by go generate; DO NOT EDIT.\npackage evm\nimport (\"errors\"; \"math\"; \"unsafe\"; \"github.com/andreyvit/evm/values\")\n" + body))
	must(err)
	if len(os.Args) > 1 && os.Args[1] == "-check" {
		existing, err := os.ReadFile("coverage_run.go")
		must(err)
		if !bytes.Equal(existing, out) {
			panic("coverage interpreter is stale: run go generate ./evm")
		}
		return
	}
	must(os.WriteFile("coverage_run.go", out, 0644))
}
func must(err error) {
	if err != nil {
		panic(fmt.Sprint(err))
	}
}
